"""Separate raw staging, run observations, deduplicated issues and immutable audit events."""

from sqlalchemy import (
    JSON,
    Boolean,
    CheckConstraint,
    Column,
    DateTime,
    ForeignKey,
    Integer,
    MetaData,
    Numeric,
    String,
    Table,
    Text,
    UniqueConstraint,
    func,
)

metadata = MetaData()
versions = Table(
    "dq_schema_migrations",
    metadata,
    Column("version", Integer, primary_key=True),
    Column("name", String(100), nullable=False),
    Column("applied_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
)
datasets = Table(
    "dq_datasets",
    metadata,
    Column("name", String(64), primary_key=True),
    Column("version", Integer, nullable=False),
    Column("content_hash", String(64), nullable=False),
    Column("metadata_json", JSON, nullable=False),
    Column("status", String(20), nullable=False),
    Column("updated_at", DateTime(timezone=True), nullable=False),
    CheckConstraint("version > 0"),
    CheckConstraint("status IN ('staged','validated','quarantined','approved')"),
)
records = Table(
    "dq_staging_records",
    metadata,
    Column("id", Integer, primary_key=True),
    Column("dataset", ForeignKey("dq_datasets.name"), nullable=False, index=True),
    Column("entity", String(30), nullable=False),
    Column("record_ref", String(80), nullable=False),
    Column("payload", JSON, nullable=False),
    Column("quarantined", Boolean, nullable=False, default=False),
    Column("is_deleted", Boolean, nullable=False, default=False),
    Column("updated_at", DateTime(timezone=True), nullable=False),
    UniqueConstraint("dataset", "entity", "record_ref"),
)
runs = Table(
    "dq_validation_runs",
    metadata,
    Column("id", Integer, primary_key=True),
    Column("dataset", ForeignKey("dq_datasets.name"), nullable=False, index=True),
    Column("dataset_version", Integer, nullable=False),
    Column("content_hash", String(64), nullable=False),
    Column("config_json", JSON, nullable=False),
    Column("report_json", JSON, nullable=False),
    Column("started_at", DateTime(timezone=True), nullable=False),
    Column("completed_at", DateTime(timezone=True), nullable=False),
    Column("reference_at", DateTime(timezone=True), nullable=False),
    Column("overall_score", Numeric(10, 6)),
    Column("failed_records", Integer, nullable=False),
)
issues = Table(
    "dq_issues",
    metadata,
    Column("id", Integer, primary_key=True),
    Column("fingerprint", String(64), nullable=False, unique=True),
    Column("dataset", ForeignKey("dq_datasets.name"), nullable=False, index=True),
    Column("rule_id", String(20), nullable=False),
    Column("rule_version", String(20), nullable=False),
    Column("entity", String(30), nullable=False),
    Column("record_ref", String(80), nullable=False),
    Column("field", String(80), nullable=False),
    Column("severity", String(20), nullable=False),
    Column("description", Text, nullable=False),
    Column("remediation", Text, nullable=False),
    Column("medicine_ref", String(80)),
    Column("batch_ref", String(80)),
    Column("first_run_id", ForeignKey("dq_validation_runs.id"), nullable=False),
    Column("last_run_id", ForeignKey("dq_validation_runs.id"), nullable=False),
    Column("detected_at", DateTime(timezone=True), nullable=False),
    Column("last_seen_at", DateTime(timezone=True), nullable=False),
    Column("status", String(20), nullable=False, index=True),
    Column("resolution_notes", Text),
    Column("resolved_at", DateTime(timezone=True)),
    CheckConstraint("severity IN ('critical','error','warning')"),
    CheckConstraint("status IN ('open','acknowledged','resolved','false_positive')"),
)
findings = Table(
    "dq_run_findings",
    metadata,
    Column("id", Integer, primary_key=True),
    Column("run_id", ForeignKey("dq_validation_runs.id"), nullable=False, index=True),
    Column("issue_id", ForeignKey("dq_issues.id"), nullable=False),
    UniqueConstraint("run_id", "issue_id"),
)
audit = Table(
    "dq_audit_events",
    metadata,
    Column("id", Integer, primary_key=True),
    Column("dataset", ForeignKey("dq_datasets.name"), nullable=False, index=True),
    Column("issue_id", ForeignKey("dq_issues.id")),
    Column("action", String(40), nullable=False),
    Column("actor", String(100), nullable=False),
    Column("notes", Text, nullable=False),
    Column("before_json", JSON),
    Column("after_json", JSON),
    Column("occurred_at", DateTime(timezone=True), nullable=False),
)
