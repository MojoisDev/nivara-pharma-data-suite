"""Additive automation tables; business data is never reset by workflows."""

from sqlalchemy import (
    JSON,
    CheckConstraint,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Integer,
    MetaData,
    String,
    Table,
    Text,
    UniqueConstraint,
)

metadata = MetaData()
executions = Table(
    "auto_executions",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("idempotency_key", String(160), nullable=False, unique=True),
    Column("request_hash", String(64), nullable=False),
    Column("kind", String(10), nullable=False),
    Column("actor", String(100), nullable=False),
    Column("notes", Text, nullable=False),
    Column("config_json", JSON, nullable=False),
    Column("params_json", JSON, nullable=False),
    Column("status", String(20), nullable=False, index=True),
    Column("created_at", DateTime(timezone=True), nullable=False),
    Column("started_at", DateTime(timezone=True)),
    Column("completed_at", DateTime(timezone=True)),
    Column("duration_seconds", Float),
    Column("attempts", Integer, nullable=False, default=0),
    Column("error_type", String(80)),
    Column("result_json", JSON),
    CheckConstraint("kind IN ('daily','weekly')"),
    CheckConstraint("status IN ('queued','running','succeeded','failed','timed_out')"),
)
attempts = Table(
    "auto_attempts",
    metadata,
    Column("id", Integer, primary_key=True),
    Column("execution_id", ForeignKey("auto_executions.id"), nullable=False, index=True),
    Column("number", Integer, nullable=False),
    Column("status", String(20), nullable=False),
    Column("started_at", DateTime(timezone=True), nullable=False),
    Column("completed_at", DateTime(timezone=True)),
    Column("duration_seconds", Float),
    Column("error_type", String(80)),
    UniqueConstraint("execution_id", "number"),
)
events = Table(
    "auto_events",
    metadata,
    Column("id", Integer, primary_key=True),
    Column("execution_id", ForeignKey("auto_executions.id"), index=True),
    Column("stage", String(30), nullable=False),
    Column("event", String(50), nullable=False),
    Column("details_json", JSON, nullable=False),
    Column("occurred_at", DateTime(timezone=True), nullable=False),
)
reports = Table(
    "auto_reports",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("execution_id", ForeignKey("auto_executions.id"), nullable=False, unique=True),
    Column("filename", String(100), nullable=False, unique=True),
    Column("sha256", String(64), nullable=False),
    Column("byte_size", Integer, nullable=False),
    Column("snapshot_hash", String(64), nullable=False),
    Column("summary_json", JSON, nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False),
)
alerts = Table(
    "auto_alerts",
    metadata,
    Column("id", Integer, primary_key=True),
    Column("identity", String(160), nullable=False, unique=True),
    Column("kind", String(40), nullable=False, index=True),
    Column("severity", String(20), nullable=False),
    Column("reason", Text, nullable=False),
    Column("record_ids", JSON, nullable=False),
    Column("content_hash", String(64), nullable=False),
    Column("revision", Integer, nullable=False),
    Column("notified_revision", Integer, nullable=False),
    Column("status", String(20), nullable=False, index=True),
    Column("detected_at", DateTime(timezone=True), nullable=False),
    Column("last_seen_at", DateTime(timezone=True), nullable=False),
    Column("resolved_at", DateTime(timezone=True)),
    CheckConstraint("status IN ('new','acknowledged','resolved')"),
    CheckConstraint("severity IN ('critical','error','warning')"),
)
alert_events = Table(
    "auto_alert_events",
    metadata,
    Column("id", Integer, primary_key=True),
    Column("alert_id", ForeignKey("auto_alerts.id"), nullable=False, index=True),
    Column("action", String(30), nullable=False),
    Column("actor", String(100), nullable=False),
    Column("notes", Text, nullable=False),
    Column("before_json", JSON),
    Column("after_json", JSON),
    Column("occurred_at", DateTime(timezone=True), nullable=False),
)
emails = Table(
    "auto_emails",
    metadata,
    Column("id", String(36), primary_key=True),
    Column("execution_id", ForeignKey("auto_executions.id"), nullable=False, unique=True),
    Column("filename", String(100), nullable=False, unique=True),
    Column("sha256", String(64), nullable=False),
    Column("subject", Text, nullable=False),
    Column("body_text", Text, nullable=False),
    Column("recipients_json", JSON, nullable=False),
    Column("status", String(20), nullable=False),
    Column("attempts", Integer, nullable=False, default=0),
    Column("created_at", DateTime(timezone=True), nullable=False),
    Column("delivered_at", DateTime(timezone=True)),
    Column("error_type", String(80)),
    CheckConstraint("status IN ('preview','queued','sending','sent','failed','uncertain')"),
)
mail_events = Table(
    "auto_mail_events",
    metadata,
    Column("id", Integer, primary_key=True),
    Column("email_id", ForeignKey("auto_emails.id"), nullable=False),
    Column("attempt", Integer, nullable=False),
    Column("status", String(30), nullable=False),
    Column("error_type", String(80)),
    Column("occurred_at", DateTime(timezone=True), nullable=False),
)
scheduler_state = Table(
    "auto_scheduler_state",
    metadata,
    Column("id", String(20), primary_key=True),
    Column("owner", String(36), nullable=False),
    Column("status", String(20), nullable=False),
    Column("heartbeat_at", DateTime(timezone=True), nullable=False),
    Column("jobs_json", JSON, nullable=False),
    Column("config_json", JSON, nullable=False),
)
